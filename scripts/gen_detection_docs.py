"""Regenerate docs/detections.md from the rule files and the latest evaluation."""
import json
from pathlib import Path

from abuseradar.rules import load_rules

root = Path(__file__).resolve().parent.parent
ev = json.loads((root / "results" / "eval.json").read_text())
prec = {b["rule_id"]: b for b in ev["by_rule"]}
out = ["# Detection catalog", "", "Generated by `scripts/gen_detection_docs.py` from `rules/*.yml` and `results/eval.json`.", "",
       "| ID | Detection | ATT&CK | Severity | Test alerts | Precision |", "|---|---|---|---|---:|---:|"]
for r in load_rules():
    p = prec.get(r.id, {})
    out.append(f"| {r.id} | {r.name} | {r.mitre} | {r.severity} | {p.get('alerts', 0)} | "
               f"{p.get('precision', 0) * 100:.1f}% |" if p else f"| {r.id} | {r.name} | {r.mitre} | {r.severity} | 0 | n/a |")
for r in load_rules():
    out += ["", f"## {r.id}: {r.name}", "", f"**ATT&CK:** {r.mitre}  ", f"**Severity:** {r.severity}  ", f"**Entity:** `{r.entity}`", "",
            r.description, "", f"**Known false positives:** {r.false_positives or 'none documented'}", "",
            f"**Response:** {r.response}", "", "```sql", r.sql.strip(), "```"]
(root / "docs" / "detections.md").write_text("\n".join(out) + "\n")
print("wrote docs/detections.md")
